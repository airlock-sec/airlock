"""The published documentation site (task 8.6).

The site is the artefact a reader meets before the code, so it is held to the same bar as the
scanner: every link resolves, every page says which page it is, and no published file carries a
string the rule engine would have reported. The design constraints the site was built under (no
gradients, no rounded corners, no shadows, one accent colour) are asserted here as well, because
a visual rule that nothing checks is a rule that decays quietly.

The rule-reference page and the hero counts are generated by `scripts/build_site.py`; that
generator has its own tests in `test_build_site.py`.
"""

