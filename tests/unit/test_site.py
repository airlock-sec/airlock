class Page(HTMLParser):
    """Every tag, id and anchor text on one page, in document order."""

    def __init__(self, name: str) -> None:
        super().__init__(convert_charrefs=True)
        self.name = name
        self.text = (SITE / name).read_text(encoding="utf-8")
        self.tags: list[tuple[str, dict[str, str]]] = []
        self.ids: list[str] = []
        self.anchors: list[tuple[dict[str, str], str]] = []
        self._anchor: dict[str, str] | None = None
        self._anchor_text: list[str] = []
        self.feed(self.text)
        self.close()

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        record = {key: "" if value is None else value for key, value in attrs}
        self.tags.append((tag, record))
        if "id" in record:
            self.ids.append(record["id"])
        if tag == "a":
            self._anchor = record
            self._anchor_text = []

    def handle_startendtag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        self.handle_starttag(tag, attrs)

    def handle_data(self, data: str) -> None:
        if self._anchor is not None:
            self._anchor_text.append(data)

    def handle_endtag(self, tag: str) -> None:
        if tag == "a" and self._anchor is not None:
            text = " ".join("".join(self._anchor_text).split())
            self.anchors.append((self._anchor, text))
            self._anchor = None

    def of(self, tag: str) -> list[dict[str, str]]:
        return [attrs for name, attrs in self.tags if name == tag]

    def links(self) -> list[str]:
        return [attrs["href"] for attrs, _ in self.anchors]


def parse(name: str) -> Page:
    return Page(name)


def site_files() -> list[Path]:
    return sorted(path for path in SITE.rglob("*") if path.is_file())


def strip_css_comments(text: str) -> str:
    return re.sub(r"/\*.*?\*/", "", text, flags=re.DOTALL)


@pytest.mark.parametrize("name", PAGES)
def test_the_page_chrome_is_complete(name: str) -> None:
    page = parse(name)

    assert page.text.startswith("<!doctype html>\n")
    assert page.of("html")[0]["lang"] == "en"
    assert "no-js" in page.of("html")[0]["class"].split()

    metas = page.of("meta")
    assert [meta["charset"] for meta in metas if "charset" in meta] == ["utf-8"]
    named = {meta["name"]: meta.get("content", "") for meta in metas if "name" in meta}
    assert named["viewport"] == "width=device-width, initial-scale=1"
    assert named["color-scheme"] == "dark"
    assert len(named["description"]) >= 80

    policies = {
        meta["http-equiv"].lower(): meta.get("content", "")
        for meta in metas
        if "http-equiv" in meta
    }
    assert policies == {"content-security-policy": CSP}

    props = {meta["property"]: meta.get("content", "") for meta in metas if "property" in meta}
    assert props["og:type"] == "website"
    assert props["og:title"]
    assert props["og:description"]
    expected_url = BASE_URL if name == "index.html" else BASE_URL + name
    assert props["og:url"] == expected_url

    assert [link["href"] for link in page.of("link") if link.get("rel") == "stylesheet"] == [
        "assets/site.css"
    ]
    assert [link["href"] for link in page.of("link") if link.get("rel") == "icon"] == [
        "favicon.svg"
    ]
    assert [(script.get("src"), "defer" in script) for script in page.of("script")] == [
        ("assets/site.js", True)
    ]

    assert [main.get("id") for main in page.of("main")] == ["main"]
    assert len(page.of("h1")) == 1
    assert len(page.of("footer")) == 1
    primary = [nav for nav in page.of("nav") if nav.get("aria-label") == "Primary"]
    assert len(primary) == 1
    skip = [attrs for attrs, _ in page.anchors if attrs.get("class") == "skip"]
    assert [attrs["href"] for attrs in skip] == ["#main"]


@pytest.mark.parametrize("name", PAGES)
def test_the_page_has_no_inline_style_script_or_handler(name: str) -> None:
    page = parse(name)

    assert "<style" not in page.text
    assert not re.search(r"\sstyle\s*=", page.text)
    assert not re.search(r"\son[a-z]+\s*=", page.text)
    assert page.text.count("<script") == 1


@pytest.mark.parametrize("name", PAGES)
def test_every_asset_the_page_references_exists(name: str) -> None:
    page = parse(name)

    for tag, attrs in page.tags:
        if tag == "link" and attrs.get("rel") in {"stylesheet", "icon"}:
            assert (SITE / attrs["href"]).is_file(), attrs["href"]
        if tag == "script" and attrs.get("src"):
            assert (SITE / attrs["src"]).is_file(), attrs["src"]


@pytest.mark.parametrize("name", PAGES)
def test_the_nav_marks_exactly_the_current_page(name: str) -> None:
    page = parse(name)

    current = [(attrs, text) for attrs, text in page.anchors if "aria-current" in attrs]
    assert len(current) == 1
    attrs, text = current[0]
    assert attrs["aria-current"] == "page"
    assert attrs["href"] == name
    assert text == NAV_LABELS[name]


@pytest.mark.parametrize("name", PAGES)
def test_ids_are_unique_on_the_page(name: str) -> None:
    page = parse(name)

    assert len(page.ids) == len(set(page.ids))
    for value in page.ids:
        assert re.fullmatch(r"[A-Za-z][\w:-]*", value), value


def test_every_internal_link_resolves() -> None:
    parsed = {name: parse(name) for name in PAGES}

    for name, page in parsed.items():
        for href in page.links():
            assert not href.startswith("http://"), (name, href)
            if href.startswith("https://"):
                continue
            base, _, fragment = href.partition("#")
            target = name if base == "" else base
            assert (SITE / target).is_file(), (name, href)
            if fragment and target.endswith(".html"):
                assert fragment in parsed[target].ids, (name, href)


def test_external_links_are_https_and_on_github() -> None:
    for name in PAGES:
        for href in parse(name).links():
            if href.startswith("https://"):
                assert urlparse(href).netloc == "github.com", (name, href)


