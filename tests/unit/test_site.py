def test_the_sitemap_lists_every_page_once() -> None:
    document = ET.fromstring((SITE / "sitemap.xml").read_text(encoding="utf-8"))
    namespace = {"s": "http://www.sitemaps.org/schemas/sitemap/0.9"}

    locs = [element.text for element in document.findall("s:url/s:loc", namespace)]
