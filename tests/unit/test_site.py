def test_no_published_file_carries_a_rule_match() -> None:
    rules = load_rules(REPO_ROOT / "rules" / "builtin")

    for path in site_files():
        text = path.read_text(encoding="utf-8")
        entry = FileEntry(
            path=path.relative_to(REPO_ROOT).as_posix(),
            sha256=None,
            roles=("source",),
            text=text,
        )
        hits = apply_patterns(rules, entry, BOOTSTRAP_POLICY.line_cap)
        assert hits == (), (entry.path, [hit.rule_id for hit in hits])
        assert cap_findings(rules, entry, BOOTSTRAP_POLICY.line_cap) == (), entry.path


def test_the_pages_workflow_publishes_the_site() -> None:
    text = WORKFLOW.read_text(encoding="utf-8")

    assert "branches: [main]" in text
    assert "workflow_dispatch" in text

    references = re.findall(r"uses:\s*(\S+)", text)
    assert len(references) == 4
    for reference in references:
        name, _, sha = reference.partition("@")
        assert re.fullmatch(r"[0-9a-f]{40}", sha), reference
        assert name

    assert "actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1" in text
    assert "actions/setup-python@6d4fd22b20465ccc0f7354476588e8df7c9ca0e0" in text
    assert "actions/upload-pages-artifact@fc324d3547104276b827a68afc52ff2a11cc49c9" in text
    assert "actions/deploy-pages@368f82528645a54fb793d4d04e342629a3f51346" in text

    permissions = text.split("permissions:", 1)[1].split("jobs:", 1)[0]
    assert "contents: read" in permissions
    assert "pages: write" in permissions
    assert "id-token: write" in permissions

    assert "python scripts/build_site.py --check" in text
    assert "path: ./site" in text or "path: site" in text
    assert "needs: build" in text
    assert "environment:" in text
    assert "name: github-pages" in text
